export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  let text = dict[lang][key] ?? dict['zh-TW'][key] ?? key
  for (const [k, v] of Object.entries(params)) text = text.replace(`%${k}%`, String(v))
  return text
}
